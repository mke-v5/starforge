// Serializes the web game's data tables (parts catalogue, preset ships) into Luau source.
import { PARTS, SIZES, RES, CATS, WING_LIMITS } from '/home/claude/starforge-pkg/src/ship/parts.js';
import { PRESETS } from '/home/claude/starforge-pkg/src/ship/designs.js';
import fs from 'fs';
const ident = /^[A-Za-z_][A-Za-z0-9_]*$/;
function lua(v, ind = '') {
  if (v === null || v === undefined) return 'nil';
  if (typeof v === 'number') return Number.isFinite(v) ? (Number.isInteger(v) ? String(v) : String(+v.toPrecision(15))) : (v > 0 ? 'math.huge' : '-math.huge');
  if (typeof v === 'boolean') return String(v);
  if (typeof v === 'string') return JSON.stringify(v);
  const i2 = ind + '\t';
  if (Array.isArray(v)) {
    const flat = v.every((x) => typeof x !== 'object' || x === null);
    if (flat) return '{ ' + v.map((x) => lua(x)).join(', ') + ' }';
    return '{\n' + v.map((x) => i2 + lua(x, i2) + ',').join('\n') + '\n' + ind + '}';
  }
  const ks = Object.keys(v).filter((k) => v[k] !== undefined);
  const parts = ks.map((k) => `${ident.test(k) ? k : '[' + JSON.stringify(k) + ']'} = ${lua(v[k], i2)}`);
  const one = '{ ' + parts.join(', ') + ' }';
  if (one.length < 140 && !one.includes('\n')) return one;
  return '{\n' + parts.map((p) => i2 + p + ',').join('\n') + '\n' + ind + '}';
}
const hdr = '-- GENERATED by gen/dump.mjs from the web game\'s data. Do not edit by hand.\n';
fs.writeFileSync('/home/claude/rbx/src/PartsData.luau', hdr + 'return ' + lua({ SIZES, RES, CATS, WING_LIMITS, PARTS }) + '\n');
fs.writeFileSync('/home/claude/rbx/src/DesignsData.luau', hdr + 'return ' + lua(PRESETS.map((p) => ({ key: p.key, blurb: p.blurb, design: p.make() }))) + '\n');
